def _load_neoasset_metadata(path: Path) -> dict[str, Mapping[str, object]]:
    if not path.exists():
        return {}
    loaded = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(loaded, Mapping):
        return {}
    instruments = loaded.get("instruments")
    if not isinstance(instruments, Sequence) or isinstance(instruments, str | bytes):
        return {}
    result: dict[str, Mapping[str, object]] = {}
    for item in instruments:
        if isinstance(item, Mapping):
            ticker = _string(item.get("ticker"))
            if ticker:
                result[ticker] = {str(key): value for key, value in item.items()}
    return result


