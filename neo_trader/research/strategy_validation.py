def _int_mapping(value: object) -> dict[str, int]:
    mapping = _mapping(value)
    result: dict[str, int] = {}
    for key, item in mapping.items():
        try:
            result[str(key)] = int(str(item))
        except ValueError:
            continue
    return result


def _decimal_mapping(values: Mapping[str, Decimal]) -> dict[str, str]:
    return {key: str(value) for key, value in sorted(values.items())}


def _decimal_dict(value: object) -> dict[str, Decimal]:
    return {
        key: _decimal_from_string(item)
        for key, item in _mapping(value).items()
    }


def _mapping(value: object) -> Mapping[str, object]:
    return value if isinstance(value, Mapping) else {}


def _sequence(value: object) -> tuple[object, ...]:
    if isinstance(value, Sequence) and not isinstance(value, str | bytes | bytearray):
        return tuple(value)
    return ()


def _code_tuple(value: str) -> tuple[str, ...]:
    return tuple(item for item in value.split("|") if item)


def _parse_datetime(value: str) -> datetime:
    return _as_utc(datetime.fromisoformat(value.replace("Z", "+00:00")))


def _optional_decimal(value: object) -> Decimal | None:
    if value is None or isinstance(value, bool):
        return None
    try:
        if isinstance(value, Decimal):
            return value if value.is_finite() else None
        if isinstance(value, int | str):
            parsed = Decimal(value)
            return parsed if parsed.is_finite() else None
        if isinstance(value, float):
            parsed = Decimal(str(value))
            return parsed if parsed.is_finite() else None
    except (InvalidOperation, ValueError):
        return None
    return None


def _decimal(value: object, field_name: str) -> Decimal:
    parsed = _optional_decimal(value)
    if parsed is None:
        raise ValueError(f"{field_name} must be a finite decimal.")
    return parsed


def _decimal_from_string(value: object) -> Decimal:
    return _optional_decimal(value) or Decimal("0")


def _decimal_or_none_string(value: Decimal | None) -> str | None:
    return None if value is None else str(value)


def _string(value: object) -> str:
    return "" if value is None else str(value)


def _as_utc(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value.replace(tzinfo=UTC)
    return value.astimezone(UTC)


