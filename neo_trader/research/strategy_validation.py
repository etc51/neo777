def _validation_csv_rows(payload: Mapping[str, object]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    strategies = _mapping(payload.get("strategies"))
    for strategy_name, strategy_value in strategies.items():
        strategy = _mapping(strategy_value)
        metrics = _mapping(strategy.get("metrics"))
        rows.append(
            {
                "section": "strategy",
                "strategy": strategy_name,
                "name": "summary",
                "trades": metrics.get("trades", 0),
                "total_pnl": metrics.get("total_pnl", "0"),
                "profit_factor": metrics.get("profit_factor"),
                "max_drawdown": metrics.get("max_drawdown", "0"),
                "winrate": metrics.get("winrate", "0"),
            }
        )
        for instrument, values in _mapping(strategy.get("instrument_metrics")).items():
            row: dict[str, object] = {
                "section": "instrument",
                "strategy": strategy_name,
                "name": str(instrument),
            }
            row.update(_mapping(values))
            rows.append(row)
        for scenario, values in _mapping(strategy.get("stress_tests")).items():
            scenario_metrics = _mapping(values)
            rows.append(
                {
                    "section": "stress",
                    "strategy": strategy_name,
                    "name": scenario,
                    "trades": scenario_metrics.get("trades", 0),
                    "total_pnl": scenario_metrics.get("total_pnl", "0"),
                    "profit_factor": scenario_metrics.get("profit_factor"),
                    "max_drawdown": scenario_metrics.get("max_drawdown", "0"),
                    "winrate": scenario_metrics.get("winrate", "0"),
                }
            )
    for item in _sequence(_mapping(payload.get("next_universe")).get("instruments")):
        if isinstance(item, Mapping):
            rows.append(
                {
                    "section": "next_universe",
                    "strategy": "",
                    "name": item.get("ticker", ""),
                    "enabled": item.get("enabled", False),
                    "score": item.get("score", "0"),
                    "reason": item.get("reason", ""),
                }
            )
    return rows


